_PROTECT = re.compile(r"(<(script|style|textarea)\b.*?</\2\s*>)", re.S | re.I)
_NODE = re.compile(r"(<[^<>]*>)([^<>]+)(?=<)")
_SPACE = re.compile(r"\s+")


def translate_html(html: str, extra: dict = None) -> str:
    """แทนข้อความไทยที่เป็น text node ทั้งก้อนด้วยคำแปล (extra = คำแปลเพิ่ม เช่น ชื่อแผนกภาษาอังกฤษ)"""
    table = EN if not extra else dict(EN, **extra)

    def node(m):
        tag, text = m.group(1), m.group(2)
        key = _SPACE.sub(" ", text).strip()
        new = table.get(key)
        if new is None or (tag[:7].lower() == "<option" and "value=" not in tag):
            return m.group(0)
        lead = text[:len(text) - len(text.lstrip())]
        tail = text[len(text.rstrip()):]
        return tag + lead + new + tail

    parts = _PROTECT.split(html)
    out, i = [], 0
    while i < len(parts):
        out.append(_NODE.sub(node, parts[i]))
        if i + 1 < len(parts):
            out.append(parts[i + 1])        # บล็อกที่ไม่แตะ
        i += 3
    return "".join(out).replace('<html lang="th"', '<html lang="en"', 1)
